// func pointwise4x8(wt, in, out *float32, b *[4]float32, cin, n, end, relu int)
TEXT ·pointwise4x8(SB), NOSPLIT, $0-64
	MOVD wt+0(FP), R0
	MOVD in+8(FP), R1
	MOVD out+16(FP), R2
	MOVD b+24(FP), R3
	MOVD cin+32(FP), R4
	MOVD n+40(FP), R5
	MOVD end+48(FP), R6
	MOVD relu+56(FP), R13
	LSL  $2, R5, R7 // a row of in or out, in bytes
	VEOR V25.B16, V25.B16, V25.B16
	VLD1 (R3), [V24.S4]
	MOVD $0, R8 // p

loopP:
	CMP  R6, R8
	BGE  done
	VDUP V24.S[0], V16.S4
	VDUP V24.S[0], V17.S4
	VDUP V24.S[1], V18.S4
	VDUP V24.S[1], V19.S4
	VDUP V24.S[2], V20.S4
	VDUP V24.S[2], V21.S4
	VDUP V24.S[3], V22.S4
	VDUP V24.S[3], V23.S4
	MOVD R0, R9            // wt
	ADD  R8<<2, R1, R10    // in + p
	MOVD R4, R11           // channels left

loopC:
	VLD1.P 16(R9), [V0.S4]
	VLD1   (R10), [V1.S4, V2.S4]
	ADD    R7, R10, R10
	VDUP   V0.S[0], V4.S4
	VDUP   V0.S[1], V5.S4
	VDUP   V0.S[2], V6.S4
	VDUP   V0.S[3], V7.S4
	VFMLA  V4.S4, V1.S4, V16.S4
	VFMLA  V4.S4, V2.S4, V17.S4
	VFMLA  V5.S4, V1.S4, V18.S4
	VFMLA  V5.S4, V2.S4, V19.S4
	VFMLA  V6.S4, V1.S4, V20.S4
	VFMLA  V6.S4, V2.S4, V21.S4
	VFMLA  V7.S4, V1.S4, V22.S4
	VFMLA  V7.S4, V2.S4, V23.S4
	SUBS   $1, R11, R11
	BNE    loopC

	CBZ    R13, store
	VFMAX  V25.S4, V16.S4, V16.S4
	VFMAX  V25.S4, V17.S4, V17.S4
	VFMAX  V25.S4, V18.S4, V18.S4
	VFMAX  V25.S4, V19.S4, V19.S4
	VFMAX  V25.S4, V20.S4, V20.S4
	VFMAX  V25.S4, V21.S4, V21.S4
	VFMAX  V25.S4, V22.S4, V22.S4
	VFMAX  V25.S4, V23.S4, V23.S4

store:
	ADD  R8<<2, R2, R12 // out + p
	VST1 [V16.S4, V17.S4], (R12)
	ADD  R7, R12, R12
	VST1 [V18.S4, V19.S4], (R12)
	ADD  R7, R12, R12
	VST1 [V20.S4, V21.S4], (R12)
	ADD  R7, R12, R12
	VST1 [V22.S4, V23.S4], (R12)
	ADD  $8, R8, R8
	B    loopP

done:
	RET

